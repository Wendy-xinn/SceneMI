"""Shared native30 x0 denoiser with patch/region conditions and pose feedback.

The correction operates inside sampling: root translation and local SO(3)
residuals alter x0, then all global joint channels are regenerated by FK.
"""
import numpy as np
import torch
from torch import nn
from pytorch3d.transforms import axis_angle_to_matrix

from experiments.offline_camera_retrain_v1.scene_model import OfflineSceneMI, cosine_alphas
from experiments.offline_camera_retrain_v1.supervision import IDENTITY_6D, forward_kinematics
from experiments.offline_camera_retrain_v1.orientation_supervision import global_rotations
from experiments.offline_camera_retrain_v1.unified_geometry import skin_points
from experiments.offline_camera_retrain_v1.native30_observations import sanitize_observations, observation_derivatives


def reconcile_motion(motion, rest, translation_m=None, rotation_axis_angle=None):
    """Rigid root moves all joints; local rotations move descendants with fixed bones."""
    root=motion[...,:3] if translation_m is None else motion[...,:3]+translation_m/2
    six_raw=motion[...,3:135].reshape(*motion.shape[:2],22,6)+motion.new_tensor(IDENTITY_6D)
    first_norm=six_raw[...,:3].norm(dim=-1,keepdim=True)
    first=six_raw[...,:3]/first_norm.clamp_min(1e-6)
    second_raw=six_raw[...,3:]-(first*six_raw[...,3:]).sum(-1,keepdim=True)*first
    second_norm=second_raw.norm(dim=-1,keepdim=True)
    second=second_raw/second_norm.clamp_min(1e-6)
    local=torch.stack((first,second,torch.cross(first,second,dim=-1)), -1)
    valid=(first_norm[...,0]>1e-6)&(second_norm[...,0]>1e-6)
    local=torch.where(valid[...,None,None],local,torch.eye(3,device=motion.device,dtype=motion.dtype))
    if rotation_axis_angle is not None:
        local=axis_angle_to_matrix(rotation_axis_angle)@local
    six=torch.cat((local[..., :,0],local[..., :,1]), -1)-motion.new_tensor(IDENTITY_6D)
    provisional=torch.cat((root,six.flatten(2),motion[...,135:]), -1)
    joints=forward_kinematics(provisional,rest)
    return torch.cat((root,six.flatten(2),joints.flatten(2)/2), -1)


class Native30SceneMI(OfflineSceneMI):
    def constrain_motion(self,motion,timestep,batch):
        return motion

    def __init__(self, latent_dim=256, dim_mults=(1,2,4), root_limit_m=.08,
                 rotation_limit_rad=.12, feedback_gain=1.):
        super().__init__(latent_dim,dim_mults,body_conditioning=True,contact_prediction=False)
        # Fresh training: a small nonzero shared output gives condition
        # encoders body-loss gradients immediately. The old20 decoder and
        # checkpoints retain their original initialization unchanged.
        nn.init.normal_(self.core.unet.final_conv[-1].weight,std=.001)
        # The old ten-feature projection is replaced, preventing a second
        # unmasked route around the confidence-aware anatomical encoder.
        self.core.sparse_control_process=nn.Identity()
        self.joint_embedding=nn.Embedding(22,16)
        self.observation_encoder=nn.Sequential(nn.Linear(43,64),nn.SiLU(),nn.Linear(64,32))
        self.observation_projection=nn.Linear(22*32,64,bias=False)
        self.camera_encoder=nn.Sequential(nn.Linear(49,128),nn.SiLU(),nn.Linear(128,64,bias=False))
        self.patch_projection=nn.Linear(1024,64)
        self.patch_position=nn.Linear(3,64,bias=False)
        self.motion_query=nn.Linear(201,64)
        self.region_embedding=nn.Embedding(22,64)
        self.patch_attention=nn.MultiheadAttention(64,4,batch_first=True)
        self.patch_condition=nn.Linear(22*64,64,bias=False)
        self.owner_embedding=nn.Embedding(128,8)
        self.dynamic_embedding=nn.Sequential(nn.Linear(19,64),nn.SiLU(),nn.Linear(64,64))
        self.dynamic_attention=nn.MultiheadAttention(64,4,batch_first=True)
        self.dynamic_condition=nn.Linear(22*64,64,bias=False)
        self.surface_embedding=nn.Sequential(nn.Linear(22,64),nn.SiLU(),nn.Linear(64,64))
        self.anchor_embedding=nn.Embedding(67,64)
        self.anchor_query=nn.Linear(14,64)
        self.surface_attention=nn.MultiheadAttention(64,4,batch_first=True)
        self.region_condition=nn.Linear(22*64,self.core.cond_latent_dim,bias=False)
        self.contact_readout=nn.Linear(64,1)
        self.contact_pose=nn.Sequential(nn.Linear(13,64),nn.SiLU(),nn.Linear(64,64))
        self.correspondence_readout=nn.Linear(64,1)
        # Full-window temporal convolutions propagate local evidence to nearby
        # frames. Joint slots survive until the rotation/output projection.
        self.feedback_temporal=nn.Sequential(nn.Conv1d(22*64,256,5,padding=2),nn.SiLU(),
                                             nn.Conv1d(256,128,5,padding=2),nn.SiLU())
        self.root_feedback=nn.Conv1d(128,3,1)
        self.rotation_feedback=nn.Conv1d(128,22*3,1)
        for layer in (self.root_feedback,self.rotation_feedback):
            nn.init.zeros_(layer.weight);nn.init.zeros_(layer.bias)
        self.register_buffer('alphas',cosine_alphas(),persistent=False)
        xy=torch.stack(torch.meshgrid(torch.arange(4),torch.arange(4),indexing='ij'),-1).reshape(16,2)
        self.register_buffer('patch_centres',torch.stack(((xy[:,0]+.5)*3.2-6.4,
            torch.full((16,),-.7),(xy[:,1]+.5)*3.2-6.4),-1),persistent=False)
        self.root_limit_m,self.rotation_limit_rad,self.feedback_gain=root_limit_m,rotation_limit_rad,feedback_gain
        self.camera_enabled=True;self.patch_enabled=True;self.local_enabled=True;self.feedback_enabled=True
        self._sampling_scene=None

    def observation_condition(self,batch,control_mask=None):
        trajectory,meta=sanitize_observations(batch['trajectory'],batch['observation_meta'])
        if control_mask is not None:
            meta=meta.clone();meta[...,:4]*=control_mask[...,None]
            trajectory,meta=sanitize_observations(trajectory,meta)
        v,a,w,dm=observation_derivatives(trajectory,meta)
        cp,cr=meta[...,2],meta[...,3]
        vc=torch.zeros_like(cp);vc[:,1:]=torch.minimum(cp[:,1:],cp[:,:-1])
        ac=torch.zeros_like(cp);ac[:,2:]=torch.minimum(vc[:,2:],vc[:,1:-1])
        wc=torch.zeros_like(cr);wc[:,1:]=torch.minimum(cr[:,1:],cr[:,:-1])
        derivatives=torch.cat((v/.15*vc[...,None],a*ac[...,None],w/np.deg2rad(20)*wc[...,None]), -1).clamp(-20,20)
        active=meta[...,:2].amax(-1)>0
        ids=self.joint_embedding.weight[None,None].expand(*trajectory.shape[:2],-1,-1)
        values=torch.cat((trajectory[...,:3]*cp[...,None],trajectory[...,3:]*cr[...,None],meta[...,:4],
                          derivatives,dm.to(trajectory),torch.nan_to_num(batch['observation_uncertainty']),ids),-1)
        confidence=(cp+cr)/meta[...,:2].sum(-1).clamp_min(1)
        encoded=self.observation_encoder(values)*active[...,None]*confidence[...,None]
        return self.observation_projection(encoded.flatten(2)),trajectory,meta

    def camera_condition(self,batch,trajectory,meta):
        camera=torch.nan_to_num(batch['camera']);available=batch['camera_available'].to(camera)
        confidence=torch.nan_to_num(batch['camera_confidence']).clamp(0,1)*available
        pm=(confidence[...,0]>0)&torch.isfinite(batch['camera'][...,:3]).all(-1)
        rm=(confidence[...,1]>0)&torch.isfinite(batch['camera'][...,3:]).all(-1)
        safe=torch.cat((torch.where(pm[...,None],camera[...,:3],0.),torch.where(rm[...,None],camera[...,3:],0.)), -1)
        self_view=batch['camera_context'][:,0]>0
        weights=meta[...,2]*meta[...,0]
        reference=(trajectory[...,:3]*weights[...,None]).sum(2)/weights.sum(2).clamp_min(1)[...,None]
        refvalid=weights.sum(2)>0
        relative=torch.where((pm&refvalid)[...,None],safe[...,:3]-reference,0.)
        mv=batch['mount_valid'];mount=torch.cat((batch['mount_translation_m']/.1,
            batch['mount_rotation'][...,:2].transpose(-1,-2).flatten(1)), -1)
        mount=torch.where(mv[:,None]>0,mount,0.)
        pose=torch.cat((relative,safe[...,3:]*confidence[...,1,None]), -1)
        pose=torch.where(self_view[:,None,None],mount[:,None].expand(-1,len(camera[0]),-1),pose)
        cm=meta.new_zeros(*camera.shape[:2],1,5)
        cm[...,0,0]=pm;cm[...,0,1]=rm;cm[...,0,2:4]=confidence
        v,a,w,dm=observation_derivatives(safe[:,:,None],cm)
        derivatives=torch.cat((v/.15,a,w/np.deg2rad(20)), -1).squeeze(2).clamp(-20,20)
        derivatives=torch.where(self_view[:,None,None],0.,derivatives);dm=dm.squeeze(2).to(camera)
        dm=torch.where(self_view[:,None,None],0.,dm)
        intrvalid=batch['camera_intrinsics_valid'];intr=torch.where(intrvalid[...,None]>0,batch['camera_intrinsics'],0.)
        context=torch.cat((batch['camera_context'],mount,mv[:,None],batch['mount_uncertainty']/camera.new_tensor([.05,np.deg2rad(10)])), -1)
        features=torch.cat((pose,torch.stack((pm,rm),-1).to(camera),confidence,intr,intrvalid[...,None],
            context[:,None].expand(-1,camera.shape[1],-1),refvalid[...,None].to(camera),derivatives,dm), -1)
        gate=torch.maximum(confidence[...,0]*pm,confidence[...,1]*rm)
        return self.camera_encoder(torch.nan_to_num(features))*gate[...,None]

    def scene_tokens(self,batch):
        vit=self.core.scene_embedding
        p=vit.to_patch_embedding(batch['occupancy']);b,n,_=p.shape
        x=torch.cat((vit.cls_token.expand(b,-1,-1),p),1)
        x=vit.transformer(vit.dropout(x+vit.pos_embedding[:,:n+1]))
        summary=vit.mlp_head(vit.to_latent(x[:,0]))
        tokens=self.patch_projection(x[:,1:])+self.patch_position(self.patch_centres)[None]
        # Empty voxel patches are UNKNOWN. A null token is always available.
        valid=(batch['occupancy'].reshape(b,24,4,12,4,12).amax((1,3,5))>0).flatten(1)
        tokens=tokens*valid[...,None]
        dynamic=[]
        for surface in batch['surface_windows']:
            features=torch.as_tensor(surface.dynamic_features,device=tokens.device,dtype=tokens.dtype)
            mask=torch.as_tensor(surface.dynamic_valid,device=tokens.device)
            owner=torch.as_tensor(surface.dynamic_owner_ids,device=tokens.device)
            ids=self.owner_embedding(owner.clamp(0,127))[None].expand(features.shape[0],-1,-1)
            encoded=self.dynamic_embedding(torch.cat((features,ids),-1))*mask[...,None]
            dynamic.append((encoded,mask))
        return summary,tokens,valid,dynamic

    def _core_pass(self,noisy,timestep,batch,scene,control_mask,use_scene,use_control,query_motion=None):
        obs,trajectory,meta=self.observation_condition(batch,control_mask if use_control else torch.zeros_like(meta_mask(batch)))
        condition=obs
        if self.camera_enabled:
            condition=condition+self.camera_condition(batch,trajectory,meta)
        if use_scene and self.patch_enabled:
            _,tokens,valid,_=scene;b,frames=noisy.shape[:2]
            query=self.motion_query(noisy if query_motion is None else query_motion)[:,:,None]+self.region_embedding.weight[None,None]
            null=tokens.new_zeros(b,1,64);keys=torch.cat((tokens,null),1)
            padding=torch.cat((~valid,valid.new_zeros(b,1)),1)
            context,_=self.patch_attention(query.flatten(1,2),keys,keys,key_padding_mask=padding,need_weights=False)
            context=context.reshape(b,frames,22,64)*valid.any(-1)[:,None,None,None]
            condition=condition+self.patch_condition(context.flatten(2))
        if use_scene:
            per_body=[]
            query=self.motion_query(noisy if query_motion is None else query_motion)[:,:,None]+self.region_embedding.weight[None,None]
            for b,(tokens,valid) in enumerate(scene[3]):
                keys=torch.cat((tokens,tokens.new_zeros(tokens.shape[0],1,64)),1)
                padding=torch.cat((~valid,valid.new_zeros(valid.shape[0],1)),1)
                context,_=self.dynamic_attention(query[b],keys,keys,key_padding_mask=padding,need_weights=False)
                per_body.append(context*valid.any(-1)[:,None,None])
            condition=condition+self.dynamic_condition(torch.stack(per_body).flatten(2))
        def control_hook(module,inputs,output):
            return condition
        ch=self.core.sparse_control_process.register_forward_hook(control_hook)
        # Avoid recomputing ViT using an ordinary temporary forward hook.
        original=self.core.scene_embedding.forward
        self.core.scene_embedding.forward=lambda *_:scene[0]
        try:
            safe=dict(batch,trajectory=trajectory)
            return super().forward(noisy,timestep,safe,control_mask=meta[...,:2].amax(-1)>0,
                                   use_scene=use_scene,use_control=use_control)
        finally:
            ch.remove();self.core.scene_embedding.forward=original

    def local_geometry(self,proposal,timestep,batch):
        rotations=global_rotations(proposal); all_context=[];all_details=[];all_bps=[];all_valid=[]
        signal=self.alphas[timestep].sqrt();fine=signal.square()
        for b,(asset,scene) in enumerate(zip(batch['skin_assets'],batch['surface_windows'])):
            vertices=skin_points(proposal[b],asset);labels=asset['labels'];r=rotations[b,:,labels]
            trajectory,meta=sanitize_observations(batch['trajectory'][b:b+1],batch['observation_meta'][b:b+1])
            observed=trajectory[0,:,labels,:3]*2;pm=meta[0,:,labels,0]>0
            # Wide reliable-joint context early; exact predicted skin anchors late.
            observed_weight=(1-fine[b])*meta[0,:,labels,2:3]*pm[...,None]
            centres=(1-observed_weight)*vertices+observed_weight*observed
            query=scene.query(centres.detach().cpu().numpy(),r.detach().cpu().numpy())
            details={k:torch.as_tensor(v,device=proposal.device) for k,v in query.items()}
            delta=details['points']-vertices[:,:,None,None]
            local=torch.einsum('taik,tasni->tasnk',r,delta)
            normal=torch.einsum('taik,tasni->tasnk',r,details['normals'])*details['normal_reliable'][...,None]
            velocity=torch.einsum('taik,tasni->tasnk',r,details['velocities'])
            distance=local.norm(dim=-1,keepdim=True)
            feat=torch.cat((local,distance,normal,-(local*normal).sum(-1,keepdim=True),
                details['normal_reliable'][...,None].to(local),(details['owners']>0)[...,None].to(local),
                velocity,details['velocity_valid'][...,None].to(local),self.owner_embedding(details['owners'].clamp(0,127))), -1)
            valid=details['valid']; feat=torch.where(valid[...,None],feat,0.)
            token=self.surface_embedding(feat).flatten(2,3);frames=len(proposal[b])
            keys=token.reshape(frames*67,24,64);keys=torch.cat((keys,keys.new_zeros(frames*67,1,64)),1)
            padding=torch.cat((~valid.reshape(frames*67,24),valid.new_zeros(frames*67,1)),1)
            body_velocity=torch.zeros_like(vertices)
            body_velocity[1:]=torch.diff(vertices,dim=0)*30
            pose6=torch.cat((r[..., :,0],r[..., :,1]),-1)
            reliability=meta[0,:,labels,2:3]
            aq_features=torch.cat((vertices/2,(body_velocity/.2).clamp(-20,20),pose6,
                signal[b].expand(frames,67,1),reliability),-1)
            aq=self.anchor_embedding.weight[None]+self.anchor_query(aq_features)
            context,_=self.surface_attention(aq.reshape(-1,1,64),keys,keys,key_padding_mask=padding,need_weights=False)
            context=context.reshape(frames,67,64)*valid.flatten(2).any(-1)[...,None]
            region=torch.stack([context[:,labels==j].mean(1) for j in range(22)],1)
            region_valid=torch.stack([valid[:,labels==j].flatten(1).any(-1) for j in range(22)],1)
            all_context.append(region);all_bps.append(torch.where(valid[:,:,2,0,None],local[:,:,2,0],0.)/2)
            all_valid.append(valid[:,:,2,0]);details.update(vertices=vertices,labels=labels,
                closest_points=details['points'][:,:,2,0],closest_normals=details['normals'][:,:,2,0],
                closest_valid=valid[:,:,2,0],closest_normal_valid=details['normal_reliable'][:,:,2,0],
                closest_velocity=details['velocities'][:,:,2,0],closest_velocity_valid=details['velocity_valid'][:,:,2,0],
                closest_owner=details['owners'][:,:,2,0],region_valid=region_valid)
            all_details.append(details)
        return torch.stack(all_context),torch.stack(all_bps),torch.stack(all_valid),all_details

    def forward(self,noisy_motion,timestep,batch,*,control_mask=None,use_scene=True,use_control=True,return_details=False):
        if noisy_motion.shape[-1]!=201 or not torch.isfinite(noisy_motion).all():
            raise ValueError('Finite native body diffusion state required')
        if self._sampling_scene is not None and (self.training or self._sampling_scene[0] is not batch['occupancy']):
            raise ValueError('Static scene token cache is scoped to one evaluation sampling call')
        scene=(self._sampling_scene[1] if self._sampling_scene is not None else self.scene_tokens(batch)) if use_scene else (noisy_motion.new_zeros(len(noisy_motion),self.core.latent_dim),None,None,None)
        # Predict proposal without GT or random-xt skin queries. Stop-gradient
        # proposal is the same architecture in training and sampling.
        with torch.no_grad():
            proposal=self._core_pass(noisy_motion,timestep,batch,scene,control_mask,use_scene,use_control)
            proposal=reconcile_motion(proposal,batch['rest'])
            proposal=self.constrain_motion(proposal,timestep,batch)
        details={}; fine=self.alphas[timestep].square()[:,None,None]
        if use_scene and self.local_enabled:
            context,bps,valid,geometry=self.local_geometry(proposal.detach(),timestep,batch)
            local=self.region_condition(context.flatten(2))*fine
            final=dict(batch,bps=bps*fine[...,None],bps_valid=valid,body_local_embedding=local)
        else:
            context=noisy_motion.new_zeros(*noisy_motion.shape[:2],22,64);geometry=[]
            final=dict(batch,bps=torch.zeros_like(batch['bps']),bps_valid=torch.zeros_like(batch['bps_valid']))
        raw=self._core_pass(noisy_motion,timestep,final,scene,control_mask,use_scene,use_control,proposal.detach())
        safe_body=reconcile_motion(raw,batch['rest'])
        body_positions=forward_kinematics(safe_body,batch['rest']);body_rotations=global_rotations(safe_body)
        body_velocity=torch.zeros_like(body_positions);body_velocity[:,1:]=torch.diff(body_positions,dim=1)*30
        pose_features=torch.cat((body_positions/2,(body_velocity/.2).clamp(-20,20),
            body_rotations[..., :,0],body_rotations[..., :,1],self.alphas[timestep].sqrt()[:,None,None,None].expand(*body_positions.shape[:3],1)), -1)
        contact=self.contact_readout(context+self.contact_pose(pose_features))[...,0]
        correspondence=self.correspondence_readout(context)[...,0]
        root_delta=raw.new_zeros(*raw.shape[:2],3);rot_delta=raw.new_zeros(*raw.shape[:2],22,3)
        if use_scene and self.local_enabled and self.feedback_enabled:
            reliability=torch.stack([g['region_valid'] for g in geometry])
            # Predicted contact affects actual motion, not just an auxiliary BCE.
            support=contact.sigmoid()*correspondence.sigmoid()*reliability
            gated=context*support[...,None]
            hidden=self.feedback_temporal(gated.flatten(2).transpose(1,2))
            frame_valid=reliability.any(-1)[...,None]
            root_direction=torch.tanh(self.root_feedback(hidden).transpose(1,2))
            root_direction=root_direction/root_direction.norm(dim=-1,keepdim=True).clamp_min(1)
            rotation_direction=torch.tanh(self.rotation_feedback(hidden).transpose(1,2)).reshape(*raw.shape[:2],22,3)
            rotation_direction=rotation_direction/rotation_direction.norm(dim=-1,keepdim=True).clamp_min(1)
            root_delta=root_direction*self.root_limit_m*fine*frame_valid*support.amax(-1,keepdim=True)*self.feedback_gain
            rot_delta=rotation_direction*self.rotation_limit_rad*fine[...,None]*support[...,None]*self.feedback_gain
        result=reconcile_motion(raw,batch['rest'],root_delta,rot_delta)
        unconstrained=result
        result=self.constrain_motion(result,timestep,batch)
        details.update(raw_motion=raw,proposal=proposal.detach(),root_delta_m=root_delta,rotation_delta_rad=rot_delta,
                       observation_root_delta_m=(result[...,:3]-unconstrained[...,:3])*2,
                       region_context=context,contact_logits=contact,correspondence_logits=correspondence,
                       geometry=geometry,feedback_gate=fine)
        return (result,details) if return_details else result


def meta_mask(batch):
    return batch['observation_meta'][...,:2].amax(-1)>0


@torch.no_grad()
def sample_native30(model,batch,*,steps=20,seed=777,use_scene=True,use_control=True):
    """Full-window DDIM with static tokens reused only within this call."""
    from experiments.offline_camera_retrain_v1.scene_model import ddim_sample
    if model._sampling_scene is not None:raise ValueError('Nested sampling scene cache')
    was_training=model.training;model.eval()
    try:
        if use_scene:model._sampling_scene=(batch['occupancy'],model.scene_tokens(batch))
        return ddim_sample(model,batch,batch['camera'].shape[1],steps=steps,seed=seed,
                           use_scene=use_scene,use_control=use_control)
    finally:
        model._sampling_scene=None;model.train(was_training)
